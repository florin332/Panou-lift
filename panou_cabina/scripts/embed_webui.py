"""PlatformIO pre-build script: embeds the web/ assets into a generated C++ header.

Reads web/index.html, web/app.css and web/app.js and writes
$BUILD_DIR/generated/WebUiContent.h with PROGMEM string constants:
WEBUI_INDEX_HTML, WEBUI_APP_CSS, WEBUI_APP_JS.
The header is only rewritten when the content actually changes, so
incremental builds are not invalidated unnecessarily.
"""

Import("env")  # noqa: F821  (provided by PlatformIO)
import os

PROJECT_DIR = env.subst("$PROJECT_DIR")  # noqa: F821
BUILD_DIR = env.subst("$BUILD_DIR")  # noqa: F821
OUT_DIR = os.path.join(BUILD_DIR, "generated")
OUT_FILE = os.path.join(OUT_DIR, "WebUiContent.h")
DELIM = "WEBUI_ASSET"

ASSETS = [
    ("WEBUI_INDEX_HTML", os.path.join(PROJECT_DIR, "web", "index.html")),
    ("WEBUI_APP_CSS", os.path.join(PROJECT_DIR, "web", "app.css")),
    ("WEBUI_APP_JS", os.path.join(PROJECT_DIR, "web", "app.js")),
]


def build_header():
    parts = [
        "// Auto-generated by scripts/embed_webui.py - do not edit.",
        "#pragma once",
        "#include <Arduino.h>",
        "",
    ]
    for symbol, path in ASSETS:
        with open(path, "r", encoding="utf-8", newline="") as handle:
            content = handle.read()
        if ")" + DELIM + '"' in content:
            raise SystemExit("embed_webui: raw-string delimiter collision in " + path)
        parts.append('const char %s[] PROGMEM = R"%s(%s)%s";' % (symbol, DELIM, content, DELIM))
        parts.append("")
    return "\n".join(parts)


os.makedirs(OUT_DIR, exist_ok=True)
header = build_header()

previous = None
if os.path.exists(OUT_FILE):
    with open(OUT_FILE, "r", encoding="utf-8", newline="") as handle:
        previous = handle.read()

if previous != header:
    with open(OUT_FILE, "w", encoding="utf-8", newline="") as handle:
        handle.write(header)
    print("embed_webui: regenerated " + OUT_FILE)

env.Append(CPPPATH=[OUT_DIR])  # noqa: F821
